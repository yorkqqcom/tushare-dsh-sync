def scaffold_adapter(api_id: str, *, force: bool = False) -> dict[str, Any]:
    meta = get_api(api_id)
    if not meta:
        known = [str(a.get("id")) for a in list_apis()]
        return {"ok": False, "error": f"unknown api id: {api_id}", "known": known}
    if bool(meta.get("implemented")):
        return {
            "ok": False,
            "error": f"{api_id} already implemented; scaffold is for coming_soon only",
            "implemented": True,
        }
    SCAFFOLD_DIR.mkdir(parents=True, exist_ok=True)
    init_path = SCAFFOLD_DIR / "__init__.py"
    if not init_path.exists():
        init_path.write_text(
            '"""Scaffold stubs only — never imported by run-pipeline hot path."""\n',
            encoding="utf-8",
        )
    out = SCAFFOLD_DIR / f"{api_id}.py"
    if out.exists() and not force:
        return {
            "ok": False,
            "error": f"already exists: {out} (pass force=true to overwrite)",
            "path": str(out),
        }
    out.write_text(_stub_source(meta), encoding="utf-8")
    return {
        "ok": True,
        "id": api_id,
        "path": str(out),
        "doc_id": meta.get("doc_id"),
        "note": "stub only; not wired into pipeline",
    }
